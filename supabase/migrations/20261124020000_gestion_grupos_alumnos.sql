-- Borrado definitivo limitado al grupo del docente; nunca elimina identidades/PIN compartidos.
BEGIN;
CREATE TABLE IF NOT EXISTS public.evento_eliminacion_grupo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 docente_id uuid NOT NULL REFERENCES public.docente(id),
 grupo_id bigint NOT NULL, alumno_id bigint,
 accion text NOT NULL CHECK(accion IN ('eliminar_grupo','eliminar_alumno_grupo')),
 registrado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
 intentos_eliminados integer NOT NULL CHECK(intentos_eliminados>=0)
);
ALTER TABLE public.evento_eliminacion_grupo ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.evento_eliminacion_grupo FROM PUBLIC,anon,authenticated,laravel_app;
GRANT SELECT ON public.evento_eliminacion_grupo TO laravel_app;
DROP POLICY IF EXISTS evento_eliminacion_grupo_docente ON public.evento_eliminacion_grupo;
CREATE POLICY evento_eliminacion_grupo_docente ON public.evento_eliminacion_grupo FOR SELECT TO laravel_app
 USING(docente_id=public.app_docente_id());

CREATE OR REPLACE FUNCTION public.fn_eliminar_alumno_grupo(p_grupo bigint,p_alumno bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_cantidad integer;
BEGIN
 PERFORM 1 FROM public.grupo WHERE id=p_grupo AND docente_id=public.app_docente_id() FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'No disponible' USING ERRCODE='P3001'; END IF;
 PERFORM 1 FROM public.alumno_grupo WHERE grupo_id=p_grupo AND alumno_id=p_alumno FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'No disponible' USING ERRCODE='P3001'; END IF;
 PERFORM e.id FROM public.examen e WHERE e.grupo_id=p_grupo FOR UPDATE;
 PERFORM i.id FROM public.intento_examen i JOIN public.examen e ON e.id=i.examen_id
 WHERE e.grupo_id=p_grupo AND i.alumno_id=p_alumno FOR UPDATE OF i;
 IF EXISTS(SELECT 1 FROM public.intento_examen i JOIN public.examen e ON e.id=i.examen_id
 WHERE e.grupo_id=p_grupo AND i.alumno_id=p_alumno AND i.estado='en_progreso')
 THEN RAISE EXCEPTION 'Examen en curso' USING ERRCODE='P3002'; END IF;
 DELETE FROM public.historial_calificacion h USING public.respuesta_alumno r,public.intento_examen i,public.examen e
 WHERE h.respuesta_alumno_id=r.id AND r.intento_id=i.id AND i.examen_id=e.id AND e.grupo_id=p_grupo AND i.alumno_id=p_alumno;
 DELETE FROM public.cierre_intento c USING public.intento_examen i,public.examen e
 WHERE c.intento_id=i.id AND i.examen_id=e.id AND e.grupo_id=p_grupo AND i.alumno_id=p_alumno;
 DELETE FROM public.tiempo_pregunta_intento t USING public.intento_examen i,public.examen e
 WHERE t.intento_id=i.id AND i.examen_id=e.id AND e.grupo_id=p_grupo AND i.alumno_id=p_alumno;
 DELETE FROM public.intento_examen i USING public.examen e WHERE i.examen_id=e.id AND e.grupo_id=p_grupo AND i.alumno_id=p_alumno;
 GET DIAGNOSTICS v_cantidad=ROW_COUNT;
 DELETE FROM public.calificacion_rubro c USING public.rubro_evaluacion r,public.evaluacion e
 WHERE c.rubro_id=r.id AND r.evaluacion_id=e.id AND e.grupo_id=p_grupo AND c.alumno_id=p_alumno;
 DELETE FROM public.alumno_grupo WHERE grupo_id=p_grupo AND alumno_id=p_alumno;
 INSERT INTO public.evento_eliminacion_grupo(docente_id,grupo_id,alumno_id,accion,intentos_eliminados)
 VALUES(public.app_docente_id(),p_grupo,p_alumno,'eliminar_alumno_grupo',v_cantidad);
 RETURN jsonb_build_object('accion','alumno_eliminado','grupo_id',p_grupo,'alumno_id',p_alumno,'intentos_eliminados',v_cantidad);
END; $fn$;

CREATE OR REPLACE FUNCTION public.fn_eliminar_grupo_docente(p_grupo bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
DECLARE v_cantidad integer;
BEGIN
 PERFORM 1 FROM public.grupo WHERE id=p_grupo AND docente_id=public.app_docente_id() FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'No disponible' USING ERRCODE='P3001'; END IF;
 PERFORM e.id FROM public.examen e WHERE e.grupo_id=p_grupo FOR UPDATE;
 PERFORM i.id FROM public.intento_examen i JOIN public.examen e ON e.id=i.examen_id WHERE e.grupo_id=p_grupo FOR UPDATE OF i;
 IF EXISTS(SELECT 1 FROM public.intento_examen i JOIN public.examen e ON e.id=i.examen_id WHERE e.grupo_id=p_grupo AND i.estado='en_progreso')
 THEN RAISE EXCEPTION 'Examen en curso' USING ERRCODE='P3002'; END IF;
 DELETE FROM public.historial_calificacion h USING public.respuesta_alumno r,public.intento_examen i,public.examen e
 WHERE h.respuesta_alumno_id=r.id AND r.intento_id=i.id AND i.examen_id=e.id AND e.grupo_id=p_grupo;
 DELETE FROM public.cierre_intento c USING public.intento_examen i,public.examen e
 WHERE c.intento_id=i.id AND i.examen_id=e.id AND e.grupo_id=p_grupo;
 DELETE FROM public.tiempo_pregunta_intento t USING public.intento_examen i,public.examen e
 WHERE t.intento_id=i.id AND i.examen_id=e.id AND e.grupo_id=p_grupo;
 DELETE FROM public.intento_examen i USING public.examen e WHERE i.examen_id=e.id AND e.grupo_id=p_grupo;
 GET DIAGNOSTICS v_cantidad=ROW_COUNT;
 -- Las FK eliminan exámenes, apartados, asociaciones, evaluaciones/rubros/notas e inscripciones.
 -- El banco de preguntas, los pagos y los perfiles/PIN de alumnos se conservan.
 DELETE FROM public.grupo WHERE id=p_grupo;
 INSERT INTO public.evento_eliminacion_grupo(docente_id,grupo_id,accion,intentos_eliminados)
 VALUES(public.app_docente_id(),p_grupo,'eliminar_grupo',v_cantidad);
 RETURN jsonb_build_object('accion','grupo_eliminado','grupo_id',p_grupo,'intentos_eliminados',v_cantidad);
END; $fn$;

-- Evita crear un intento con una inscripción eliminada por otra transacción.
CREATE OR REPLACE FUNCTION public.fn_comprobar_inscripcion_intento() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $fn$
BEGIN
 IF NEW.estado='en_progreso' THEN
  PERFORM 1 FROM public.examen e JOIN public.grupo g ON g.id=e.grupo_id
  JOIN public.alumno_grupo ag ON ag.grupo_id=g.id AND ag.alumno_id=NEW.alumno_id
  WHERE e.id=NEW.examen_id AND g.activo FOR KEY SHARE OF g,ag;
  IF NOT FOUND THEN RAISE EXCEPTION 'Inscripción no disponible' USING ERRCODE='P0001'; END IF;
 END IF;
 RETURN NEW;
END; $fn$;
DROP TRIGGER IF EXISTS comprobar_inscripcion_intento ON public.intento_examen;
CREATE TRIGGER comprobar_inscripcion_intento BEFORE INSERT ON public.intento_examen
FOR EACH ROW EXECUTE FUNCTION public.fn_comprobar_inscripcion_intento();
REVOKE ALL ON FUNCTION public.fn_eliminar_alumno_grupo(bigint,bigint),public.fn_eliminar_grupo_docente(bigint),public.fn_comprobar_inscripcion_intento() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.fn_eliminar_alumno_grupo(bigint,bigint),public.fn_eliminar_grupo_docente(bigint) TO laravel_app;
COMMIT;
SELECT to_regprocedure('public.fn_eliminar_grupo_docente(bigint)') IS NOT NULL AS eliminar_grupo,
 to_regprocedure('public.fn_eliminar_alumno_grupo(bigint,bigint)') IS NOT NULL AS eliminar_alumno_grupo,
 to_regclass('public.evento_eliminacion_grupo') IS NOT NULL AS auditoria_eliminacion;
